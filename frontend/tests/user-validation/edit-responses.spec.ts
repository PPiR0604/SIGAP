import {test,expect} from '@playwright/test';

test('edit live bergantian dan rename mempertahankan cakupan posko serta menghitung kandidat tanpa write',async({page},testInfo)=>{
  test.setTimeout(300_000);
  const errors:string[]=[];let writes=0;
  page.on('pageerror',error=>errors.push(error.message));
  await page.route(/^https:\/\/fonts\.(googleapis|gstatic)\.com\//,r=>r.abort());
  await page.route('**/api/batches/*/decisions',r=>{writes++;return r.abort();});
  const connected=page.waitForResponse(r=>r.url().endsWith('/api/sessions')&&r.ok());
  await page.goto('/');await connected;
  const token=await page.evaluate(()=>localStorage.getItem('sigap_token'));
  const batch=async(id:string)=>await(await page.request.get(`/api/batches/${id}`,{headers:{Authorization:`Bearer ${token}`}})).json();
  const composer=page.getByRole('textbox',{name:'Laporan atau pertanyaan Anda'});
  await composer.fill('Periksa kebutuhan di semua desa berdasarkan rekap tersimpan. Hanya membaca.');
  const accepted=page.waitForResponse(r=>/\/messages$/.test(r.url())&&r.ok());
  await page.getByRole('button',{name:'Kirim',exact:true}).click();
  const initial=(await(await accepted).json()).batch_id;
  await expect.poll(async()=>(await batch(initial)).status,{timeout:60000,intervals:[1000,2000]}).toBe('conversation_done');
  await page.getByRole('button',{name:'Rekap',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(8);
  const open=async(name:string,village:string)=>{
    await page.locator('tbody tr').filter({has:page.getByRole('button',{name,exact:true})}).filter({hasText:village}).getByRole('button',{name,exact:true}).click();
    const dialog=page.getByRole('dialog',{name:'Detail laporan'});
    await dialog.getByRole('button',{name:'Tulis klarifikasi'}).click();return dialog;
  };
  const submit=async(dialog:ReturnType<typeof page.getByRole>)=>{
    const accepted=page.waitForResponse(r=>/\/messages$/.test(r.url())&&r.ok());
    await dialog.getByRole('button',{name:'Validasi perubahan'}).click();
    const id=(await(await accepted).json()).batch_id;let result:any;
    await expect.poll(async()=>{
      result=await batch(id);
      return ['failed','payload_invalid','needs_review'].includes(result.status)||result.gap?.automatic_recalculation===true;
    },{timeout:140000,intervals:[1000,2000,5000]}).toBe(true);
    expect(result.status).toBe('ready_for_review');
    await expect(dialog.getByRole('button',{name:'Tulis klarifikasi'})).toBeEnabled({timeout:15000});
    await expect(dialog.getByRole('alert')).toHaveCount(0);
    await expect(dialog.getByRole('status')).toContainText('Kebutuhan sudah dihitung ulang');
    return result;
  };
  let dialog=await open('Posko Harapan','Sukamaju');
  await dialog.getByRole('spinbutton',{name:'Jumlah jiwa',exact:true}).fill('102');
  await dialog.getByRole('spinbutton',{name:'Laki-laki',exact:true}).fill('47');
  await dialog.getByRole('spinbutton',{name:'Disabilitas',exact:true}).fill('2');
  const a=await submit(dialog);expect(a.preview.records[0].total_people).toBe(102);
  await dialog.getByRole('button',{name:'Tutup dialog'}).click();
  dialog=await open('Posko Cibening','Cibineng');
  await dialog.getByRole('spinbutton',{name:'Jumlah jiwa',exact:true}).fill('104');
  await dialog.getByRole('spinbutton',{name:'Laki-laki',exact:true}).fill('57');
  await dialog.getByRole('spinbutton',{name:'Perempuan',exact:true}).fill('47');
  const b=await submit(dialog);expect(b.preview.records[0].total_people).toBe(104);
  await dialog.getByRole('button',{name:'Tulis klarifikasi'}).click();
  await dialog.getByRole('textbox',{name:'Catatan klarifikasi (opsional)'}).fill('Koreksi nama posko ini menjadi Posko Cibening Utama. Semua angka dan kebutuhan tetap sama.');
  const renamed=await submit(dialog);
  expect(renamed.preview.records[0].shelter_name).toBe('Posko Cibening Utama');
  await expect(dialog.getByRole('heading',{name:'Posko Cibening Utama',exact:true})).toBeVisible();
  await expect(dialog.getByRole('region',{name:'Hasil perhitungan kebutuhan'})).toContainText('1.560 L/hari');
  await dialog.getByRole('button',{name:'Tutup dialog'}).click();
  await expect(page.locator('tbody tr')).toHaveCount(8);
  await expect(page.getByLabel('Kandidat untuk disetujui').locator('option')).toHaveCount(2);
  const harapan=page.locator('tbody tr').filter({has:page.getByRole('button',{name:'Posko Harapan',exact:true})});
  await expect(harapan.filter({hasText:'Sukamaju'}).locator('.population')).toHaveText('102');
  await expect(harapan.filter({hasText:'Cipandan'}).locator('.population')).toHaveText('40');
  await page.getByRole('button',{name:'Posko Cibening Utama',exact:true}).click();
  await page.getByRole('button',{name:'Tinjau & simpan perubahan'}).click();
  await expect(page.locator('.approval-scope')).toContainText('Posko Cibening Utama');
  await expect(page.locator('.approval-scope')).not.toContainText('Posko Harapan');
  await page.getByRole('button',{name:'Kembali periksa'}).click();
  await page.screenshot({path:testInfo.outputPath('edit-live-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:testInfo.outputPath('edit-live-mobile.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);expect(writes).toBe(0);
  await testInfo.attach('edit-live-summary',{contentType:'application/json',body:Buffer.from(JSON.stringify({shelters:8,pending_candidates:2,harapan_people:102,cibening_people:104,rename:renamed.preview.records[0].shelter_name,external_write:false}))});
});
