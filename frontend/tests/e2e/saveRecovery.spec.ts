 let cursor=0;
 const events:{id:number;body:string}[]=[];
 const emit=(event:string,data:any)=>{const id=++cursor;events.push({id,body:`id: ${id}\nevent: ${event}\ndata: ${JSON.stringify(data)}\n\n`});};
